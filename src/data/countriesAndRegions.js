export const getCountryByCode = (code) => {
  if (!code) return null;
  return COUNTRIES.find((c) => c.code.toUpperCase() === code.toUpperCase()) || null;
};

export const getCountryByName = (name) => {
  if (!name) return null;
  return COUNTRIES.find((c) => c.name.toLowerCase() === name.toLowerCase()) || null;
};

export const formatLocationDisplay = (stateRegion, countryName) => {
  const parts = [stateRegion, countryName].map((s) => (s || '').trim()).filter(Boolean);
  if (parts.length === 0) return 'Worldwide';
  return parts.join(', ');
};
